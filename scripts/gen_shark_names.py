#!/usr/bin/env python3
"""Generate shark_names.py: the names tshark gives protocol values that
Suricata logs by name (NT status codes, FSCTL functions), from
`tshark -G values` - so a SHAR-CRATES run doesn't load tshark's 1.6
million value names to find a few.

Usage: python3 scripts/gen_shark_names.py > shark_names.py
Rerun after upgrading tshark."""

import subprocess
import sys

TABLES = {
    'NT_STATUS': 'smb2.nt_status',        # STATUS_SUCCESS, ... (SMB1 and SMB2 share them)
    'FSCTL': 'smb2.ioctl.function',       # FSCTL_DFS_GET_REFERRALS, ...
}


def main():
    version = subprocess.run(['tshark', '-v'], capture_output=True, text=True).stdout.splitlines()[0]
    values = subprocess.run(['tshark', '-G', 'values'], capture_output=True, text=True, errors='replace').stdout
    found = {name: {} for name in TABLES}
    field_table = {field: name for name, field in TABLES.items()}
    for line in values.splitlines():
        parts = line.split('\t')
        if len(parts) == 4 and parts[0] == 'V' and parts[1] in field_table:
            found[field_table[parts[1]]].setdefault(int(parts[2], 0), parts[3])
    print('"""Names tshark gives values Suricata logs by name - generated by')
    print(f'scripts/gen_shark_names.py from {version}; do not edit."""')
    for name, table in found.items():
        print(f'\n{name} = {{')
        for value, text in sorted(table.items()):
            print(f'    {value:#x}: {text!r},')
        print('}')


if __name__ == '__main__':
    sys.exit(main())
